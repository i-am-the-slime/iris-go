// Command collationgen writes go-support/prim/collation_table.go: the weights
// that golang.org/x/text/collate's CLDR root collation, which is the ICU root
// collation JavaScript's localeCompare uses, gives each code point. It is its
// own module, so that go-support itself has no dependencies.
//
//	cd go-support/internal/collationgen && go run . ../../prim/collation_table.go
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"golang.org/x/text/collate"
	"golang.org/x/text/language"
)

// weights is one code point's sort key, split into its levels.
type weights [3][]byte

func main() {
	collator := collate.New(language.Und)
	var buffer collate.Buffer
	weightsOf := func(r rune) weights {
		if r >= 0xD800 && r < 0xE000 {
			// ICU orders a lone surrogate as an unassigned code point.
			return weights{{0x85, byte(r >> 8), byte(r)}, {0, 0x20}, {2}}
		}
		if r == 0xFFFD {
			// ICU gives U+FFFD the highest primary weight, above every
			// implicit one; x/text orders it first.
			return weights{{0xFF, 0xFF, 0xFD}, {0, 0x20}, {2}}
		}
		key := append([]byte(nil), collator.KeyFromString(&buffer, string(r))...)
		buffer.Reset()
		return levels(key)
	}
	var runs strings.Builder
	var blob bytes.Buffer
	count := 0
	var previous weights
	for r := rune(0); r <= 0x10FFFF; r++ {
		current := weightsOf(r)
		if r > 0 && successor(previous, current) {
			previous = current
			continue
		}
		fmt.Fprintf(&runs, "\t{0x%04X, %d},\n", r, blob.Len())
		blob.Write([]byte{byte(len(current[0])), byte(len(current[1])), byte(len(current[2]))})
		for _, level := range current {
			blob.Write(level)
		}
		previous = current
		count++
	}
	var out strings.Builder
	out.WriteString("// Code generated by go-support/internal/collationgen from golang.org/x/text v0.44.0; DO NOT EDIT.\n\n")
	out.WriteString("package prim\n\n")
	out.WriteString("// collationRuns divide the code points into runs, each from its start to the\n")
	out.WriteString("// next run's, whose weights are those of its first code point with the last\n")
	out.WriteString("// two bytes of the primary weight counting up by one per code point.\n")
	fmt.Fprintf(&out, "var collationRuns = [%d]collationRun{\n%s}\n\n", count, runs.String())
	out.WriteString("// collationWeights holds each run's first weights: the lengths of the primary,\n")
	out.WriteString("// secondary and tertiary weights, then their bytes.\n")
	out.WriteString("const collationWeights = \"")
	for _, b := range blob.Bytes() {
		fmt.Fprintf(&out, "\\x%02x", b)
	}
	out.WriteString("\"\n")
	if err := os.WriteFile(os.Args[1], []byte(out.String()), 0o644); err != nil {
		panic(err)
	}
}

// levels splits an x/text sort key: primary weights of two bytes (three when
// the first has its high bit set), two zero bytes, secondary weights of two
// bytes, two zero bytes, and tertiary weights of one byte.
func levels(key []byte) weights {
	var out weights
	at := 0
	for at+1 < len(key) && !(key[at] == 0 && key[at+1] == 0) {
		size := 2
		if key[at]&0x80 != 0 {
			size = 3
		}
		out[0] = append(out[0], key[at:at+size]...)
		at += size
	}
	at += 2
	for at+1 < len(key) && !(key[at] == 0 && key[at+1] == 0) {
		out[1] = append(out[1], key[at:at+2]...)
		at += 2
	}
	at += 2
	out[2] = append(out[2], key[at:]...)
	return out
}

// successor tells whether next's weights are previous's with the last two
// bytes of the primary weight one higher.
func successor(previous weights, next weights) bool {
	n := len(previous[0])
	if n < 2 || len(next[0]) != n || !bytes.Equal(previous[1], next[1]) || !bytes.Equal(previous[2], next[2]) ||
		!bytes.Equal(previous[0][:n-2], next[0][:n-2]) {
		return false
	}
	last := func(w []byte) int { return int(w[n-2])<<8 | int(w[n-1]) }
	return last(next[0]) == last(previous[0])+1
}
